#!/usr/bin/env python3
"""Generate golden lookup data for the ru_dict test.

Usage: python gen_golden.py [data_root] [out_header]
    data_root default: /home/andrey/model/ruaccent-data
    out_header default: ru_dict_testdata.h (next to this file)

Reads dictionary/<name>.json.gz, picks sample keys (first/last sorted +
fixed list) and emits expected lookups for the C++ test.
"""
import gzip
import json
import os
import sys

NAMES = ["accents", "omographs", "yo_words", "yo_homographs"]

FIXED = {
    "accents": ["коса", "дом", "молоко", "окно", "телефон", "президент",
                "обучение", "замок", "щавель", "подъезд"],
    "omographs": ["коса", "ключ", "лист", "дом", "красный", "замок",
                  "якорь", "объект", "смысл", "привет"],
    "yo_words": ["щавель", "подъезд", "съезд", "объект", "съёмка",
                 "подъём", "съём", "ящик", "съели", "подъёмник"],
    "yo_homographs": ["щавелем", "подъём", "съезд", "объектом", "съёмке",
                      "подъёма", "съём", "якорем", "съела", "подъёмник"],
}


def cstr(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    s = s.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return '"' + s + '"'


def main():
    data_root = sys.argv[1] if len(sys.argv) > 1 else "/home/andrey/model/ruaccent-data"
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "ru_dict_testdata.h")

    lines = [
        "// AUTO-GENERATED by gen_golden.py -- do not edit by hand.",
        "#pragma once",
        "#include <cstddef>",
        "#include <string>",
        "#include <vector>",
        "namespace ru_dict_test {",
        "struct Case { std::string key; std::string value; };",
        "",
    ]

    for name in NAMES:
        tag = name.upper()
        with gzip.open(os.path.join(data_root, "dictionary", f"{name}.json.gz"),
                       "rt", encoding="utf-8") as f:
            d = json.load(f)
        keys = sorted(d)
        sample = list(dict.fromkeys(keys[:3] + keys[-3:] +
                                    [k for k in FIXED[name] if k in d]))
        missing = None
        for cand in ["zzz_missing_key_0", "zzz_missing_key_1", "zzz_missing_key_2"]:
            if cand not in d:
                missing = cand
                break
        assert missing is not None

        lines.append(f"static const size_t {tag}_COUNT = {len(d)};")
        lines.append(f"static const std::vector<Case> {tag}_CASES = {{")
        for k in sample:
            v = d[k]
            if isinstance(v, list):
                v = "\n".join(v)
            lines.append(f"    {{ {cstr(k)}, {cstr(v)} }},")
        lines.append("};")
        lines.append(f"static const std::string {tag}_MISSING = {cstr(missing)};")
        lines.append("")

    lines.append("}  // namespace ru_dict_test")
    lines.append("")

    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
