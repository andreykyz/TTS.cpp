#!/usr/bin/env python3
"""Regenerate ru_g2p_testdata.h from the Python reference.

Runs kokoro-ru/ru_g2p.py RuG2P.phonemize (the ground truth the Kokoro-ru
model was trained on) over a fixed set of Russian sentences and emits the
golden IPA as a C++ header. Requires the kokoro-ru venv (ruaccent, misaki,
phonemizer) and the acute-aware espeak-data dir.

Usage: python gen_oracle.py [kokoro_ru_dir]
"""
import sys
from pathlib import Path

kokoro_ru = Path(sys.argv[1] if len(sys.argv) > 1 else "/home/andrey/model/kokoro-ru")
sys.path.insert(0, str(kokoro_ru))
from ru_g2p import RuG2P  # noqa: E402

SENTENCES = [
    "Молоко", "Мама", "Цирк", "Чай", "Джентльмен", "Дзынь", "большого", "мощный",
    "Ёжик", "мука", "Он принёс цветы", "Привет! Как дела?", "Я люблю читать книги.",
    "Щи", "Здравствуйте", "Вода в реке холодная", "Начало нового года", "Цыплёнок",
    "Чёрный", "Щётка", "Это было давно.", "Тридцать три корабля", "Собака спит",
    "Раз, два, три", "Мама, папа, я",
]


def cpp_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    g2p = RuG2P(espeak_data=str(kokoro_ru / "espeak-data"),
                vocab_path=str(kokoro_ru / "kokoro-config.json"))
    lines = [
        "// AUTO-GENERATED by gen_oracle.py -- do not edit by hand.",
        "// Golden IPA for the full Russian G2P pipeline (RUAccent stress -> acute ->",
        "// lower -> respell -> espeak -> normalize -> reduce_vowels -> lengthen_sch),",
        "// produced by the Python reference (kokoro-ru/ru_g2p.py RuG2P.phonemize).",
        "#pragma once",
        "#include <cstddef>",
        "namespace ru_g2p_test {",
        "struct Case { const char * in; const char * out; };",
        "static const Case CASES[] = {",
    ]
    for s in SENTENCES:
        ps, oov = g2p.phonemize(s)
        assert not oov, f"OOV symbols in {s!r}: {sorted(oov)}"
        lines.append(f"    {{ {cpp_str(s)}, {cpp_str(ps)} }},")
    lines.append("};")
    lines.append(f"static const std::size_t N = {len(SENTENCES)};")
    lines.append("}  // namespace ru_g2p_test")
    out = Path(__file__).with_name("ru_g2p_testdata.h")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(SENTENCES)} cases)")


if __name__ == "__main__":
    main()
