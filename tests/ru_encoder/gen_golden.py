#!/usr/bin/env python3
"""Generate reference logits (onnxruntime) + inputs for the ru_encoder test.

Usage: python gen_golden.py [--nn-dir DIR] [--out HEADER] [--seed N]

For each of the 4 RUAccent models, emits deterministic inputs (random token
ids, all-ones attention mask, random token_type_ids where applicable) and the
reference logits from onnxruntime, as a C++ header for tests/ru_encoder.
"""
import argparse
import os

import numpy as np
import onnxruntime as ort

# name: (onnx_rel, vocab, has_type, seq_lengths, batch)
MODELS = {
    "accent": ("nn_accent/model.onnx", 45, True, [5, 15, 40], 1),
    "stress": ("nn_stress_usage_predictor/model.onnx", 83828, True, [10, 30, 60], 1),
    "omograph": ("nn_omograph/turbo3.1/model.onnx", 60258, False, [20, 30, 50], 2),
    "yo": ("nn_yo_homograph_resolver/model.onnx", 5031, False, [10, 30, 60], 1),
}
SEEDS = {"accent": 101, "stress": 102, "omograph": 103, "yo": 104}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nn-dir", default="/home/andrey/model/ruaccent-data/nn")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                  "ru_encoder_testdata.h"))
    args = ap.parse_args()

    lines = [
        "// AUTO-GENERATED by gen_golden.py -- do not edit by hand.",
        "#pragma once",
        "namespace ru_enc_test {",
        "struct CaseRef {",
        "    int batch, seq, n_ids, n_type, n_logits;",
        "    const int * ids;",
        "    const int * type;",
        "    const float * logits;",
        "};",
    ]

    for name, (onnx_rel, vocab, has_type, seqs, batch) in MODELS.items():
        tag = name.upper()
        sess = ort.InferenceSession(args.nn_dir + "/" + onnx_rel,
                                    providers=["CPUExecutionProvider"])
        rng = np.random.default_rng(SEEDS[name])
        case_refs = []
        for ci, seq in enumerate(seqs):
            b = batch
            ids = rng.integers(0, vocab, size=(b, seq))
            mask = np.ones((b, seq), dtype=np.int64)
            feed = {"input_ids": ids.astype(np.int64), "attention_mask": mask}
            type_ids = None
            if has_type:
                type_ids = rng.integers(0, 2, size=(b, seq))
                feed["token_type_ids"] = type_ids.astype(np.int64)
            ref = sess.run(None, feed)[0].astype(np.float32).ravel()
            ids_f = ids.ravel()
            lines.append("static const int %s%d_ids[] = { %s };" % (
                tag, ci, ", ".join(str(int(x)) for x in ids_f)))
            if has_type:
                lines.append("static const int %s%d_type[] = { %s };" % (
                    tag, ci, ", ".join(str(int(x)) for x in type_ids.ravel())))
            lines.append("static const float %s%d_logits[] = { %s };" % (
                tag, ci, ", ".join(repr(float(x)) for x in ref)))
            n_type = type_ids.size if has_type else 0
            type_arr = ("%s%d_type" % (tag, ci)) if has_type else "nullptr"
            case_refs.append("    { %d, %d, %d, %d, %d, %s%d_ids, %s, %s%d_logits }," % (
                b, seq, ids_f.size, n_type, ref.size, tag, ci, type_arr, tag, ci))
        lines.append("static const CaseRef %s_CASES[] = {" % tag)
        lines.extend(case_refs)
        lines.append("};")
        lines.append("static const int %s_N = %d;" % (tag, len(seqs)))
        lines.append("")

    lines.append("}  // namespace ru_enc_test")
    lines.append("")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
