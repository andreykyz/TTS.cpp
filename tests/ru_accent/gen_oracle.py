#!/usr/bin/env python3
"""Generate the reference (Python RUAccent) stress outputs for the ru_accent test.

Runs the full RUAccent pipeline (process_all) on a fixed set of Russian
sentences and writes, for each, the stressed text (with '+' marks) into a C++
header (ru_accent_testdata.h). This is the oracle the C++ ru_accent component
is verified against.

Usage: python gen_oracle.py [--data-dir DIR] [--out HEADER]
"""
import argparse
import os
import sys

SENTENCES = [
    "Мама мыла раму",
    "Держи косу",
    "У косы острая кромка",
    "Объект исследования",
    "Ты видел его вчера",
    "Солнце светит ярко",
    "Она любит читать книги",
    "Вчера я был в Москве",
    "Это было дорого и красиво",
    "Купи хлеб и молоко, пожалуйста",
    "Где ты был? Я не знаю",
    "Дорога впереди длинная",
    "Он принёс цветы",
    "Начало нового года",
    "Вода в реке холодная",
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", default="/home/andrey/model/ruaccent-data")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                  "ru_accent_testdata.h"))
    args = ap.parse_args()

    sys.path.insert(0, "/home/andrey/model/tts/venv310/lib/python3.10/site-packages")
    from ruaccent import RUAccent

    os.environ.setdefault("HF_HUB_OFFLINE", "1")
    ra = RUAccent()
    ra.load(workdir=args.data_dir, omograph_model_size="turbo3.1",
            use_dictionary=True, device="CPU")

    lines = [
        "// AUTO-GENERATED by gen_oracle.py -- do not edit by hand.",
        "#pragma once",
        "#include <cstddef>",
        "namespace ru_accent_test {",
        "struct Case { const char * in; const char * out; };",
        "static const Case CASES[] = {",
    ]
    for s in SENTENCES:
        out = ra.process_all(s)
        out = out.replace("\n", " ").replace("\t", " ")
        out = out.replace('"', '\\"')
        s2 = s.replace('"', '\\"')
        lines.append('    { "%s", "%s" },' % (s2, out))
    lines.append("};")
    lines.append("static const std::size_t N = %d;" % len(SENTENCES))
    lines.append("}  // namespace ru_accent_test")
    lines.append("")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
